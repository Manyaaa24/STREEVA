"""
STREEVA — Area Risk Scoring Engine
app/services/macro_baseline_service.py

NCRB district-level crime baseline service.

Data source:
  National Crime Records Bureau (NCRB) — district-wise IPC crimes
  Original data: data.gov.in / Dataful.in
  Local processed file: data/processed/ncrb_district_lookup.json
  Generated by: scripts/ingest_ncrb.py

How this is used:
  The macro baseline provides city-level historical crime context.
  It is NOT the primary risk signal — it's a prior that shifts the
  baseline up or down relative to national/state average.

  Example: Chennai has 16,861 total IPC crimes (2014), while Ariyalur
  has only 1,615. This context matters: a "safe-looking" location in
  Chennai still carries more baseline risk than the same features in Ariyalur.

Limitations:
  - Data is from 2014 (latest year in dataset.json)
  - NCRB only publishes annual reports — this cannot update live
  - Total IPC crimes include driving offences (rash driving: 8,527 in Chennai)
    which inflates the raw count. We use a curated "violent crime" subset.
  - District-level only — applies uniformly across all H3 cells in Chennai

This is not a flaw — it is the honest design, explicitly documented.
"""

