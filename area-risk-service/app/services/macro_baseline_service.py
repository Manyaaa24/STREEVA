import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from app.config import get_city_config, get_settings
from app.utils.logger import get_logger

logger = get_logger(__name__)

# Violent crime columns used for baseline (subset of total IPC)
# Rationale: Total IPC includes rash driving (8,527 in Chennai) which
# is a traffic offence, not a violence indicator. We use a curated
# set of offences relevant to personal safety.
