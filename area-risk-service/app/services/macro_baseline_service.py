@lru_cache(maxsize=1)
def _load_district_lookup() -> dict[str, Any]:
    """
    Load the NCRB district lookup JSON from disk.
    Result is cached in memory via lru_cache.

    Returns:
        Dict mapping district name → crime stats.
        Empty dict if file not found (service will use neutral baseline).
    """
    settings = get_settings()
    lookup_path = settings.ncrb_lookup_abs

    if not lookup_path.exists():
        logger.warning(
            "ncrb_lookup_missing",
            path=str(lookup_path),
            hint="Run scripts/ingest_ncrb.py to generate the lookup file.",
        )
        return {}

    try:
        with open(lookup_path, encoding="utf-8") as f:
            data = json.load(f)
        logger.info(
            "ncrb_lookup_loaded",
            path=str(lookup_path),
            district_count=len(data),
        )
        return data
    except Exception as exc:
        logger.error("ncrb_lookup_load_failed", error=str(exc))
        return {}


def get_macro_baseline_score(district: str | None = None, lat: float | None = None, lng: float | None = None) -> tuple[float, dict[str, Any]]:
    """
    Return the macro crime baseline risk score (0–100) for a district.

    Args:
        district: District name matching NCRB data (e.g. 'Chennai').
                  If None, attempts to resolve via lat/lng, then falls back to city config.
        lat: Optional latitude to resolve district.
        lng: Optional longitude to resolve district.

    Returns:
        Tuple of (baseline_score_0_to_100, metadata_dict).
        Returns (50.0, {...}) as neutral baseline if data is unavailable.
    """
    city_config = get_city_config()
    lookup_key = district
    
    if lookup_key is None and lat is not None and lng is not None:
        try:
            from app.services.district_service import get_district_for_location
            resolved_district = get_district_for_location(lat, lng)
            if resolved_district:
                lookup_key = resolved_district
        except Exception as exc:
            logger.error("district_resolution_failed", error=str(exc))
            
    if lookup_key is None:
        lookup_key = city_config.ncrb_district_key

    lookup = _load_district_lookup()

    if not lookup:
        logger.warning("ncrb_using_neutral_baseline", reason="lookup_empty")
        return 50.0, {
            "source": "fallback_neutral",
            "district": lookup_key,
            "reason": "NCRB lookup not available. Run scripts/ingest_ncrb.py.",
        }

    district_data = lookup.get(lookup_key)
    if not district_data:
        # Try case-insensitive match
        lower_key = lookup_key.lower()
        for k, v in lookup.items():
            if k.lower() == lower_key:
                district_data = v
                lookup_key = k
                break

    if not district_data:
        logger.warning("ncrb_district_not_found", district=lookup_key)
        return 50.0, {
            "source": "fallback_neutral",
            "district": lookup_key,
            "reason": f"District '{lookup_key}' not found in NCRB lookup.",
        }

    score = float(district_data.get("normalized_score", 50.0))
    return score, {
        "source": "ncrb_2014",
        "district": lookup_key,
        "violent_crimes": district_data.get("violent_crimes", 0),
        "total_ipc_crimes": district_data.get("total_ipc_crimes", 0),
        "year": district_data.get("year", "2014"),
        "normalized_score": score,
        "state_rank": district_data.get("state_rank"),
        "state_district_count": district_data.get("state_district_count"),
        "note": district_data.get("data_year_note"),
    }
